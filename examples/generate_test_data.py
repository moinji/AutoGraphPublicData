def write_csv(domain_dir: str, table_name: str, columns: list[str], rows: list[list]):
    """Write a single CSV file."""
    path = DATA_DIR / domain_dir
    path.mkdir(parents=True, exist_ok=True)
    fp = path / f"{table_name}.csv"
    with open(fp, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(columns)
        w.writerows(rows)
    return fp


