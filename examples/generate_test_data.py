def gen_text_documents():
    """Generate MD, HTML, TXT documents for all domains."""
    for domain, docs in DOCUMENTS.items():
        domain_dir = DOC_DIR / domain
        domain_dir.mkdir(parents=True, exist_ok=True)

        for fmt in ("md", "html", "txt"):
            if fmt in docs:
                filename, content = docs[fmt]
                fp = domain_dir / filename
                with open(fp, "w", encoding="utf-8") as f:
                    f.write(content)

    count = sum(1 for d in DOCUMENTS.values() for f in ("md", "html", "txt") if f in d)
    print(f"  ✓ Text documents — {count} files (MD/HTML/TXT)")


def gen_pdf_documents():
    """Generate PDF documents using fpdf2 with Korean font."""
    from fpdf import FPDF

    font_path = r"C:\Windows\Fonts\malgun.ttf"
    if not os.path.exists(font_path):
        print("  ✗ PDF — malgun.ttf not found, skipping")
        return

    count = 0
    for domain, docs in DOCUMENTS.items():
        if "pdf_title" not in docs:
            continue

        domain_dir = DOC_DIR / domain
        domain_dir.mkdir(parents=True, exist_ok=True)

        title = docs["pdf_title"]
        content = docs["pdf_content"]

        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()
        pdf.add_font("malgun", "", font_path)
        pdf.add_font("malgun", "B", r"C:\Windows\Fonts\malgunbd.ttf")

        # Title
        pdf.set_font("malgun", "B", 16)
        pdf.cell(0, 12, title, new_x="LMARGIN", new_y="NEXT", align="C")
        pdf.ln(8)

        # Content
        pdf.set_font("malgun", "", 10)
        for line in content.split("\n"):
            stripped = line.strip()
            if stripped:
                # Replace problematic chars
                stripped = stripped.replace("·", ", ").replace("→", "->")
                try:
                    pdf.multi_cell(w=0, h=6, text=stripped)
                except Exception:
                    # Fallback: write as simple cell
                    pdf.cell(w=0, h=6, text=stripped[:80], new_x="LMARGIN", new_y="NEXT")
            else:
                pdf.ln(3)

        fp = domain_dir / f"{title}.pdf"
        pdf.output(str(fp))
        count += 1

    print(f"  ✓ PDF documents — {count} files")


def gen_docx_documents():
    """Generate DOCX documents using python-docx."""
    from docx import Document
    from docx.shared import Pt

    count = 0
    for domain, docs in DOCUMENTS.items():
        if "docx_title" not in docs:
            continue

        domain_dir = DOC_DIR / domain
        domain_dir.mkdir(parents=True, exist_ok=True)

        title = docs["docx_title"]
        elements = docs["docx_content"]

        doc = Document()
        style = doc.styles["Normal"]
        style.font.name = "맑은 고딕"
        style.font.size = Pt(11)

        for elem_type, text in elements:
            if elem_type == "heading":
                doc.add_heading(text, level=1)
            elif elem_type == "heading2":
                doc.add_heading(text, level=2)
            elif elem_type == "para":
                doc.add_paragraph(text)

        fp = domain_dir / f"{title}.docx"
        doc.save(str(fp))
        count += 1

    print(f"  ✓ DOCX documents — {count} files")


